// Builds the GitHub issue templates (.github/ISSUE_TEMPLATE/release-check-*.md) from TESTING.md, so the checklist has one source of
// truth. Run `npm run checklists` after editing TESTING.md; `npm test` fails if the templates are out of date.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const REPO = 'https://github.com/parkhilljosiah/bible-cross-reference'
const SITE = 'https://parkhilljosiah.github.io/bible-cross-reference/'

/** TESTING.md split at its "## " headings (not "### "): a Map of heading -> body, without the "---" rules between sections. */
export function sections(md) {
  const out = new Map()
  for (const part of md.split(/^## /m).slice(1)) {
    const nl = part.indexOf('\n')
    out.set(part.slice(0, nl).trim(), part.slice(nl + 1).replace(/\n*---\s*$/, '').trim())
  }
  return out
}

/** In an issue the golden links' relative addresses (`/?sel=John.3.16`) can't be clicked, so turn them into full links. */
function linkify(body) {
  const base = SITE.replace(/\/$/, '')
  return body.replace(/^\| `(\/[^`]*)` \|/gm, (_, path) => `| [\`${path}\`](${base}${path}) |`)
}

/** The section whose heading starts with `prefix` ("0. ", "Golden links"). Throws if it is missing, so a rename can't silently empty a template. */
function pick(map, prefix) {
  for (const [heading, body] of map) if (heading.startsWith(prefix)) return { heading, body }
  throw new Error(`TESTING.md has no section starting "${prefix}"`)
}

export const TEMPLATES = [
  {
    file: 'release-check-smoke.md',
    name: 'Release check (smoke test)',
    about: 'Run after every deployment: about 10 minutes, desktop and phone',
    sections: ['0. ', '1. ', '2. '],
    known: true,
  },
  {
    file: 'release-check-full.md',
    name: 'Release check (full pass)',
    about: 'Run after a new feature or a fix to one: about 30 minutes on top of the smoke test',
    sections: ['0. ', '1. ', '2. ', '3. '],
    known: true,
  },
  {
    file: 'release-check-data.md',
    name: 'Release check (data rebuilt)',
    about: 'Run after rebuilding the data with scripts/build-data.mjs',
    sections: ['0. ', '4. '],
    known: false,
  },
]

export function buildTemplate(md, spec) {
  const map = sections(md)
  const parts = [
    '---',
    `name: ${spec.name}`,
    `about: ${spec.about}`,
    'title: "Release check: "',
    "assignees: ''",
    '---',
    '<!-- Generated from TESTING.md by `npm run checklists`. Edit TESTING.md and re-run it; do not edit this file by hand. -->',
    '',
    '- **Release (commit or date):** ',
    '- **Deploy run (Actions link):** ',
    '- **Tested by / on:** ',
    '- **Devices and browsers:** ',
    '',
    `Explanations and expected values: [TESTING.md](${REPO}/blob/main/TESTING.md). Live site: ${SITE}`,
    '',
  ]
  const golden = pick(map, 'Golden links')
  const wanted = [{ ...golden, body: linkify(golden.body) }, ...spec.sections.map((p) => pick(map, p))]
  if (spec.known) wanted.push(pick(map, '5. '))
  for (const { heading, body } of wanted) parts.push(`## ${heading}`, '', body, '')
  parts.push(
    '## Problems found',
    '',
    'For each: device and OS, browser, the address (everything after the `?`), the steps, what you expected, what happened, and a screenshot.',
    '',
  )
  return parts.join('\n')
}

export function buildAll(md) {
  return TEMPLATES.map((spec) => ({ file: spec.file, content: buildTemplate(md, spec) }))
}

// Run directly: write the files.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const md = readFileSync(join(ROOT, 'TESTING.md'), 'utf8')
  const dir = join(ROOT, '.github', 'ISSUE_TEMPLATE')
  mkdirSync(dir, { recursive: true })
  for (const { file, content } of buildAll(md)) {
    writeFileSync(join(dir, file), content)
    console.log(`wrote .github/ISSUE_TEMPLATE/${file} (${(content.match(/- \[ \]/g) ?? []).length} checkboxes)`)
  }
}
